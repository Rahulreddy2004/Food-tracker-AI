// Regenerates src/lib/api/schema.d.ts from the FastAPI OpenAPI spec (single source of truth).
//   pnpm api:types
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import openapiTS, { astToString } from "openapi-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const apiDir = resolve(here, "../../api");
const out = resolve(here, "../src/lib/api/schema.d.ts");

const spec = execFileSync(
  "uv",
  [
    "run",
    "--quiet",
    "python",
    "-c",
    "import json; from app.main import create_app; print(json.dumps(create_app().openapi()))",
  ],
  { cwd: apiDir, encoding: "utf8", env: { ...process.env, LOG_LEVEL: "WARNING" } },
);
const ast = await openapiTS(JSON.parse(spec));
writeFileSync(
  out,
  "/* Generated by scripts/gen-api-types.mjs — do not edit. */\n" + astToString(ast),
);
console.log(`wrote ${out}`);

// The 101 dishes the classifier knows, for the landing page and search hints.
const labels = JSON.parse(readFileSync(resolve(apiDir, "app/data/labels.json"), "utf8"));
const dishes = labels.classes.map(({ name, display, group }) => ({ name, display, group }));
const dishesOut = resolve(here, "../src/data/dishes.json");
mkdirSync(dirname(dishesOut), { recursive: true });
writeFileSync(dishesOut, JSON.stringify(dishes) + "\n");
console.log(`wrote ${dishesOut} (${dishes.length} dishes)`);
